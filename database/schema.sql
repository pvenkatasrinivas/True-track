-- ============================================================
-- True Track - PostgreSQL schema (reference)
--
-- You do NOT have to run this file: the backend uses
--   spring.jpa.hibernate.ddl-auto=update
-- so Hibernate creates these tables automatically from the @Entity classes
-- (User.java and Task.java) the first time the app starts.
--
-- It is provided so you can see the exact tables, or create them by hand:
--   psql -U postgres -d truetrack -f database/schema.sql
-- ============================================================

CREATE TABLE IF NOT EXISTS users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    email       VARCHAR(150) NOT NULL UNIQUE,
    password    VARCHAR(100) NOT NULL,          -- BCrypt hash, never the plain password
    created_at  TIMESTAMP    NOT NULL
);

CREATE TABLE IF NOT EXISTS tasks (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(100)  NOT NULL,
    description  VARCHAR(1000),
    assigned_to  VARCHAR(100),
    priority     VARCHAR(20)   NOT NULL,        -- LOW, MEDIUM, HIGH
    status       VARCHAR(20)   NOT NULL,        -- PENDING, IN_PROGRESS, COMPLETED
    created_at   TIMESTAMP     NOT NULL,
    updated_at   TIMESTAMP     NOT NULL
);

-- Helpful indexes for the filters on the task list page
CREATE INDEX IF NOT EXISTS idx_tasks_status   ON tasks (status);
CREATE INDEX IF NOT EXISTS idx_tasks_priority ON tasks (priority);
